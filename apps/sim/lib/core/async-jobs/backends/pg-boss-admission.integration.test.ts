import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
import { JobEnvelopeSchema } from '@memlia/contracts'
import { eq, inArray } from 'drizzle-orm'
import postgres from 'postgres'

const envFile = process.env.MEMLIA_QUEUE_ADMISSION_TEST_ENV_FILE
assert.ok(envFile, 'MEMLIA_QUEUE_ADMISSION_TEST_ENV_FILE required; no integration skip')
const env = Object.fromEntries(
  readFileSync(envFile, 'utf8')
    .split('\n')
    .filter((line) => line.includes('='))
    .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)])
)
assert.ok(env.TEST_DATABASE_URL && new URL(env.TEST_DATABASE_URL).pathname.includes('_test_'))
for (const key of Object.keys(process.env)) {
  if (
    key.startsWith('DATABASE_URL') ||
    key.startsWith('DATABASE_REPLICA_URL') ||
    key === 'MIGRATION_DATABASE_URL'
  )
    delete process.env[key]
}
process.env.DATABASE_URL = env.TEST_DATABASE_URL
process.env.MEMLIA_PG_BOSS_ENABLED = '1'
process.env.MEMLIA_PG_BOSS_DATABASE_URL = env.MEMLIA_PG_BOSS_DATABASE_URL
const { db } = await import('@sim/db')
const { asyncJobs, outboxEvent } = await import('@sim/db/schema')
const { admitPgBossJob, readPgBossPublication, PG_BOSS_OUTBOX_EVENT } = await import(
  './pg-boss-admission'
)
const { pgBossOutboxHandlers } = await import('./pg-boss-outbox')
const { pgBossClient } = await import('./pg-boss-client')
const { processOutboxEventById } = await import('@/lib/core/outbox/service')
const { OUTBOX_HANDLER_GROUPS } = await import('@/lib/core/outbox/handlers')

const prefix = `admission-${randomUUID()}`
const jobs: string[] = []
const events: string[] = []
function input(label: string) {
  const jobId = `${prefix}:${label}`
  jobs.push(jobId)
  return {
    jobId,
    envelope: JobEnvelopeSchema.parse({
      schemaVersion: 'memlia.job/v1',
      commandId: 'fixture-command',
      runId: 'fixture-run',
      runner: 'workflow-execution',
      inputs: [],
      idempotencyKey: `${prefix}-fixture-key-${label}`,
      submittedAt: '2026-10-19T03:00:00.000Z',
      effectPolicy: { kind: 'no_automatic_retry' },
      authority: {
        schemaVersion: 'memlia.principal/v1',
        organizationId: 'fixture-org',
        workspaceId: 'fixture-workspace',
        actor: {
          version: 1,
          principal: { kind: 'session', userId: 'fixture-user', sessionId: 'fixture-session' },
        },
        subject: { kind: 'user', userId: 'fixture-user' },
        authority: { kind: 'interactive' },
        scopes: ['workflow:read'],
        allowedTools: ['workflows.read'],
      },
    }),
    payload: { fixture: label, nested: { a: 1, b: 2 } },
    metadata: { workspaceId: 'fixture-workspace', executionId: 'fixture-run' },
    maxDurationSeconds: 900,
  }
}
async function admit(value: ReturnType<typeof input>) {
  const result = await db.transaction((tx) => admitPgBossJob(tx, value))
  events.push(result.outboxEventId)
  return result
}
async function counts(jobId: string) {
  return (await db.select().from(asyncJobs).where(eq(asyncJobs.id, jobId))).length
}

test(
  'atomic native admission and real outbox publication on restricted PostgreSQL',
  { timeout: 30000 },
  async (t) => {
    const transportDb = postgres(env.MEMLIA_PG_BOSS_DATABASE_URL, { max: 1, onnotice: () => {} })
    t.after(async () => {
      await pgBossClient.stop()
      // Only the identities generated by this run; never clear a shared table.
      if (events.length) await db.delete(outboxEvent).where(inArray(outboxEvent.id, events))
      if (jobs.length) await db.delete(asyncJobs).where(inArray(asyncJobs.id, jobs))
      if (jobs.length)
        await transportDb`delete from memlia_jobs.job where name = 'memlia_native' and data->>'nativeJobId' in ${transportDb(jobs)}`
      await transportDb.end()
    })
    await t.test(
      'caller rollback removes both writes and no publication happens inside the transaction',
      async () => {
        const value = input('rollback')
        let eventId = ''
        await assert.rejects(
          db.transaction(async (tx) => {
            const admitted = await admitPgBossJob(tx, value)
            eventId = admitted.outboxEventId
            const event = await tx.select().from(outboxEvent).where(eq(outboxEvent.id, eventId))
            assert.equal(event.length, 1)
            assert.deepEqual(Object.keys(event[0].payload as object).sort(), [
              'admissionDigest',
              'nativeJobId',
            ])
            throw new Error('fixture-rollback')
          }),
          /fixture-rollback/
        )
        assert.equal(await counts(value.jobId), 0)
        assert.equal(
          (await db.select().from(outboxEvent).where(eq(outboxEvent.id, eventId))).length,
          0
        )
      }
    )
    await t.test(
      'concurrent identical requests keep one native job and one deterministic event',
      async () => {
        const value = input('duplicate')
        const [a, b] = await Promise.all([admit(value), admit(value)])
        assert.equal(a.jobId, value.jobId)
        assert.equal(a.outboxEventId, b.outboxEventId)
        assert.equal([a, b].filter((r) => r.duplicate).length, 1)
        assert.equal(await counts(value.jobId), 1)
        const [row] = await db.select().from(asyncJobs).where(eq(asyncJobs.id, value.jobId))
        assert.equal(row.status, 'pending')
        assert.equal(row.maxAttempts, 1)
        assert.equal(row.attempts, 0)
        const reordered = { ...value, payload: { nested: { b: 2, a: 1 }, fixture: 'duplicate' } }
        assert.equal((await admit(reordered)).duplicate, true)
      }
    )
    await t.test('different concurrent content cannot overwrite the accepted request', async () => {
      const value = input('conflict')
      const other = { ...value, payload: { ...value.payload, fixture: 'different' } }
      const results = await Promise.allSettled([admit(value), admit(other)])
      assert.equal(results.filter((r) => r.status === 'fulfilled').length, 1)
      const rejected = results.find((r) => r.status === 'rejected')
      assert.equal(
        rejected?.status === 'rejected' && rejected.reason.code,
        'admission_identity_conflict'
      )
      assert.equal(await counts(value.jobId), 1)
    })
    await t.test(
      'one scoped idempotency key cannot admit two different native identities concurrently',
      async () => {
        const value = input('key-race')
        const other = { ...value, jobId: `${value.jobId}-other` }
        jobs.push(other.jobId)
        const results = await Promise.allSettled([admit(value), admit(other)])
        assert.equal(results.filter((r) => r.status === 'fulfilled').length, 1)
        const rejected = results.find((r) => r.status === 'rejected')
        assert.equal(
          rejected?.status === 'rejected' && rejected.reason.code,
          'admission_identity_conflict'
        )
        assert.equal((await counts(value.jobId)) + (await counts(other.jobId)), 1)
      }
    )
    await t.test('retained event prevents recreation after the native job was purged', async () => {
      const value = input('purged')
      const receipt = await admit(value)
      await db.delete(asyncJobs).where(eq(asyncJobs.id, value.jobId))
      await db.transaction(async (tx) => {
        // Catching rejection must not commit the newly inserted orphan projection.
        await assert.rejects(admitPgBossJob(tx, value), {
          code: 'admission_reconciliation_required',
        })
      })
      assert.equal(await counts(value.jobId), 0)
      assert.equal(
        await processOutboxEventById(receipt.outboxEventId, pgBossOutboxHandlers),
        'pending'
      )
      const [orphan] = await db
        .select()
        .from(outboxEvent)
        .where(eq(outboxEvent.id, receipt.outboxEventId))
      assert.equal(orphan.lastError, 'admission_reconciliation_required')
      assert.equal(
        (await db.select().from(outboxEvent).where(eq(outboxEvent.id, receipt.outboxEventId)))
          .length,
        1
      )
    })
    await t.test(
      'legacy job without our admission cannot be hijacked and savepoint rolls back on caught errors',
      async () => {
        const value = input('legacy')
        await db
          .insert(asyncJobs)
          .values({ id: value.jobId, type: 'workflow-execution', payload: { legacy: true } })
        await db.transaction(async (tx) => {
          await assert.rejects(admitPgBossJob(tx, value), {
            code: 'admission_reconciliation_required',
          })
        })
        const [row] = await db.select().from(asyncJobs).where(eq(asyncJobs.id, value.jobId))
        assert.deepEqual(row.payload, { legacy: true })
      }
    )
    await t.test(
      'invalid kind, non-JSON payload and mismatched scope are rejected before writes',
      async () => {
        const value = input('invalid')
        const sparse: unknown[] & { extra?: number } = new Array(2)
        sparse[1] = 1
        sparse.extra = 3
        const hiddenExtra = [1]
        Object.defineProperty(hiddenExtra, 'extra', { value: 'must-not-disappear' })
        const hiddenObject = { visible: 1 }
        Object.defineProperty(hiddenObject, 'hidden', { value: 'must-not-disappear' })
        const overriddenMap = [1]
        let mapCalled = false
        Object.defineProperty(overriddenMap, 'map', {
          value: () => {
            mapCalled = true
            return [1]
          },
        })
        for (const invalid of [
          { ...value, payload: sparse },
          { ...value, payload: hiddenExtra },
          { ...value, payload: hiddenObject },
          { ...value, payload: overriddenMap },
          { ...value, envelope: { ...value.envelope, runner: 'run-data-drain' } },
          { ...value, payload: { lost: undefined } },
          { ...value, metadata: { ...value.metadata, workspaceId: 'foreign-workspace' } },
        ]) {
          await assert.rejects(
            db.transaction(async (tx) => {
              await admitPgBossJob(tx, invalid)
              throw new Error('Unexpected admission; rollback the negative fixture')
            }),
            { acceptance: 'rejected' }
          )
        }
        assert.equal(mapCalled, false)
        assert.equal(await counts(value.jobId), 0)
      }
    )
    await t.test(
      'registered native handler publishes once; replay preserves the transport delivery',
      async () => {
        const value = input('publish')
        const admission = await admit(value)
        const [event] = await db
          .select()
          .from(outboxEvent)
          .where(eq(outboxEvent.id, admission.outboxEventId))
        const publication = await readPgBossPublication(db, event.payload)
        assert.equal(publication.runAt, value.envelope.submittedAt)
        assert.equal(publication.maxDurationSeconds, 900)
        const group = OUTBOX_HANDLER_GROUPS.find((group) =>
          group.events.includes(PG_BOSS_OUTBOX_EVENT)
        )
        assert.ok(group, 'Default native outbox must register the event')
        const handlers = await group.load()
        assert.equal(await processOutboxEventById(admission.outboxEventId, handlers), 'completed')
        const before =
          await transportDb`select id, state, retry_limit from memlia_jobs.job where name = 'memlia_native' and data->>'nativeJobId' = ${value.jobId}`
        assert.equal(before.length, 1)
        assert.equal(before[0].state, 'created')
        assert.equal(before[0].retry_limit, 0)
        // Simulate loss of the outbox ACK after pg-boss accepted the immutable delivery.
        await db
          .update(outboxEvent)
          .set({ status: 'pending', processedAt: null })
          .where(eq(outboxEvent.id, admission.outboxEventId))
        assert.equal(
          await processOutboxEventById(admission.outboxEventId, pgBossOutboxHandlers),
          'completed'
        )
        const after =
          await transportDb`select id from memlia_jobs.job where name = 'memlia_native' and data->>'nativeJobId' = ${value.jobId}`
        assert.deepEqual(
          after.map((row) => row.id),
          before.map((row) => row.id)
        )
        assert.equal(
          (await db.select().from(asyncJobs).where(eq(asyncJobs.id, value.jobId)))[0].status,
          'pending'
        )
      }
    )
    await t.test(
      'cancelled admission is not published and disabled configuration cannot fall back to web credentials',
      async () => {
        const value = input('cancelled')
        const admission = await admit(value)
        await db
          .update(asyncJobs)
          .set({ status: 'cancelled', completedAt: new Date() })
          .where(eq(asyncJobs.id, value.jobId))
        assert.equal(
          await processOutboxEventById(admission.outboxEventId, pgBossOutboxHandlers),
          'completed'
        )
        const deliveries =
          await transportDb`select id from memlia_jobs.job where name = 'memlia_native' and data->>'nativeJobId' = ${value.jobId}`
        assert.equal(deliveries.length, 0)
        const disabled = input('disabled')
        const pending = await admit(disabled)
        process.env.MEMLIA_PG_BOSS_ENABLED = '0'
        try {
          assert.equal(
            await processOutboxEventById(pending.outboxEventId, pgBossOutboxHandlers),
            'pending'
          )
          const [event] = await db
            .select()
            .from(outboxEvent)
            .where(eq(outboxEvent.id, pending.outboxEventId))
          assert.equal(event.lastError, 'pg_boss_disabled')
        } finally {
          process.env.MEMLIA_PG_BOSS_ENABLED = '1'
        }
      }
    )
    await t.test(
      'an outbox reference copied under another event identity cannot publish',
      async () => {
        const value = input('reference-copy')
        const admission = await admit(value)
        const [original] = await db
          .select()
          .from(outboxEvent)
          .where(eq(outboxEvent.id, admission.outboxEventId))
        const copiedId = `${prefix}:copied-event`
        events.push(copiedId)
        await db.insert(outboxEvent).values({
          id: copiedId,
          eventType: PG_BOSS_OUTBOX_EVENT,
          payload: original.payload,
          availableAt: new Date(value.envelope.submittedAt),
        })
        assert.equal(await processOutboxEventById(copiedId, pgBossOutboxHandlers), 'pending')
        const [copied] = await db.select().from(outboxEvent).where(eq(outboxEvent.id, copiedId))
        assert.equal(copied.lastError, 'admission_identity_conflict')
        const deliveries =
          await transportDb`select id from memlia_jobs.job where name = 'memlia_native' and data->>'nativeJobId' = ${value.jobId}`
        assert.equal(deliveries.length, 0)
      }
    )
    await t.test(
      'handler refuses altered payload and does not publish or expose its text',
      async () => {
        const value = input('tampered')
        const admission = await admit(value)
        await db
          .update(asyncJobs)
          .set({ payload: { secretFixture: 'must-not-leak' } })
          .where(eq(asyncJobs.id, value.jobId))
        assert.equal(
          await processOutboxEventById(admission.outboxEventId, pgBossOutboxHandlers),
          'pending'
        )
        const [event] = await db
          .select()
          .from(outboxEvent)
          .where(eq(outboxEvent.id, admission.outboxEventId))
        assert.equal(event.lastError?.includes('must-not-leak'), false)
        assert.equal(event.lastError, 'admission_identity_conflict')
        const deliveries =
          await transportDb`select id from memlia_jobs.job where name = 'memlia_native' and data->>'nativeJobId' = ${value.jobId}`
        assert.equal(deliveries.length, 0)
      }
    )
  }
)
